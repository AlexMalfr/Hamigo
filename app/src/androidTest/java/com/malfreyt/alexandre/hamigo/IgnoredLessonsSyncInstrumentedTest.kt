/** Android JSON and real Progress/backup code, with preferences held exclusively in RAM. */
@RunWith(AndroidJUnit4::class)
class IgnoredLessonsSyncInstrumentedTest {
    private val context get()=InstrumentationRegistry.getInstrumentation().targetContext
    private fun progress(at:Long=1_800_000_000_000)=Progress(DiagnosticContext(context),sideEffects=false,
        clock=Clock.fixed(Instant.ofEpochMilli(at),ZoneOffset.UTC))
    private fun record(value:Any,at:Long)=JSONObject().put("value",value).put("modifiedAt",at)
    private fun state(json:String)=JSONObject(json).getJSONObject("progress")
    private fun sameJson(expected:JSONObject,actual:JSONObject)=assertEquals(CloudProgress.canonical(expected),CloudProgress.canonical(actual))
    private fun settings(progress:Progress)=SyncedAppSettings.snapshot(progress.prefs)

    @Test fun ignoringAdvancesOnlyThePathAndActualCompletionStillPaysItsNormalBonus() {
        val content=Content(context,examSnapshot=null)
        val progress=progress()
        progress.prepareLearning(content)
        val original=state(progress.export())
        val ids=(content.lessons.take(4)+content.lessons.first {it.certificateWeight>0}+
            content.lessons.first {it.explorationWeight>0}).map {it.id}.toSet()
        val originalQuestionIds=content.courseQuestions.map {it.id}
        progress.setIgnored(ids,true)
        assertEquals(ids,progress.ignored)
        assertEquals(ids,progress.pathCompleted)
        assertTrue(progress.completed.isEmpty())
        assertEquals("An ignored lesson must be reintegrated before it can be completed",0,progress.complete(ids.first()))
        assertTrue(progress.completed.isEmpty())
        assertEquals(content.lessons.first {it.id !in ids}.id,content.nextLesson(progress.pathCompleted)?.id)
        assertEquals(0,progress.xp)
        assertEquals(0,progress.totalAnswers)
        assertTrue(progress.reviews.isEmpty())
        assertTrue(progress.skillReviews.isEmpty())
        assertTrue(progress.due(content).isEmpty())
        val after=state(progress.export())
        for(key in listOf("answers","correct","reviews","skillReviews","completed")) {
            assertEquals("Ignoring changed learning evidence "+key,original.opt(key)?.toString() ?: "{}",after.opt(key)?.toString() ?: "{}")
        }
        val bar=content.pathCompletion(progress.pathCompleted)
        val expectedCertificate=content.lessons.filter {it.id in ids}.sumOf {it.certificateWeight}.toFloat()/content.lessons.sumOf {it.certificateWeight}
        val expectedExploration=content.lessons.filter {it.id in ids}.sumOf {it.explorationWeight}.toFloat()/content.lessons.sumOf {it.explorationWeight}
        assertEquals(expectedCertificate,bar.certificate,.000001f)
        assertEquals(expectedExploration,bar.exploration,.000001f)
        assertEquals(PathCompletion(0f,0f),content.pathCompletion(progress.completed))
        val snapshot=progress.snapshot(content)
        assertEquals(ids.size,snapshot.lessons)
        assertEquals(ids.size,snapshot.pathCompletedLessons)
        assertEquals(content.lessons.size,snapshot.pathTotalLessons)
        assertEquals(0,snapshot.xp)
        assertEquals(originalQuestionIds,content.courseQuestions.map {it.id})
        progress.setIgnored(ids,false)
        assertTrue(progress.ignored.isEmpty())
        assertTrue(progress.pathCompleted.isEmpty())
        assertEquals(content.lessons.first().id,content.nextLesson(progress.pathCompleted)?.id)
        assertEquals(0,progress.xp)
        progress.setIgnored(ids,true)
        assertEquals("Ignoring a lesson must never award XP",0,progress.xp)
        progress.setIgnored(ids,false)
        val laterCompleted=ids.first()
        assertEquals("Actual completion after ignoring must pay its normal bonus",6,progress.complete(laterCompleted))
        assertTrue(laterCompleted in progress.completed)
        assertEquals(6,progress.xp)
        assertEquals(0,progress.complete(laterCompleted))
        assertEquals(0,progress.totalAnswers)
        assertTrue(progress.reviews.isEmpty())
        assertTrue(progress.skillReviews.isEmpty())
    }

    @Test fun restoringAnIgnoredLessonLeavesATombstoneThatSurvivesAnOldDeviceAndRepeatedMerges() {
        val progress=progress()
        val base=progress.export()
        val selected=IgnoredLessons.update(null,setOf("lesson-a"),true,100)
        val restored=IgnoredLessons.update(selected,setOf("lesson-a"),false,200)
        val second=IgnoredLessons.update(null,setOf("lesson-b"),true,150)
        fun backup(records:JSONObject)=JSONObject(base).apply {getJSONObject("progress").put(IgnoredLessons.FIELD,records)}.toString()
        val old=backup(selected)
        val current=backup(IgnoredLessons.merge(restored,second))
        val merged=CloudProgress.merge(current,old)
        assertEquals(merged,CloudProgress.merge(old,current))
        assertEquals(merged,CloudProgress.merge(merged,old))
        assertEquals(merged,CloudProgress.merge(merged,merged))
        val records=state(merged).getJSONObject(IgnoredLessons.FIELD)
        assertFalse(records.getJSONObject("lesson-a").getBoolean("ignored"))
        assertEquals(200,records.getJSONObject("lesson-a").getLong("modifiedAt"))
        assertEquals(setOf("lesson-b"),IgnoredLessons.selected(records))
        progress.import(merged)
        progress.mergeCloud(old)
        assertEquals(setOf("lesson-b"),progress.ignored)
        assertTrue(progress.completed.isEmpty())
        assertEquals(0,progress.xp)
        // A legitimate, newer choice can ignore it again; the false record is not a permanent ban.
        val selectedAgain=IgnoredLessons.update(restored,setOf("lesson-a"),true,300)
        assertTrue("lesson-a" in IgnoredLessons.selected(IgnoredLessons.merge(restored,selectedAgain)))
        val tied=IgnoredLessons.update(null,setOf("lesson-a"),true,200)
        sameJson(IgnoredLessons.merge(restored,tied),IgnoredLessons.merge(tied,restored))
        assertFalse("lesson-a" in IgnoredLessons.selected(IgnoredLessons.merge(restored,tied)))
    }

    @Test fun speechAudioAndMorseSettingsRoundTripAndLegacyBackupsDoNotResetNewSettings() {
        val source=progress()
        SpeechInputPreferences.save(source.prefs,SpeechInputMode.TOGGLE)
        FeedbackPreferences.save(source.prefs,FeedbackSettings(sound=false,haptics=true))
        GameplayPreferences.save(source.prefs,MorseInputSettings(singleKey=true,thresholdMs=450,liveSound=false,autoSpaces=true))
        SyncedAppSettings.save(source.prefs,mapOf("autoSync" to false))
        val exported=source.export()
        assertEquals(SyncedAppSettings.keys,JSONObject(exported).getJSONObject(SyncedAppSettings.FIELD).keys().asSequence().toSet())
        fun checkRestored(target:Progress) {
            assertEquals(SpeechInputMode.TOGGLE,SpeechInputPreferences.read(target.prefs))
            assertEquals(FeedbackSettings(false,true),FeedbackPreferences.read(target.prefs))
            assertEquals(MorseInputSettings(true,450,false,true),GameplayPreferences.read(target.prefs))
            assertFalse(target.prefs.getBoolean("autoSync",true))
            assertEquals(0,target.xp)
            assertTrue(target.completed.isEmpty())
        }
        val merged=progress()
        merged.mergeCloud(exported)
        checkRestored(merged)
        val imported=progress()
        imported.import(merged.export())
        checkRestored(imported)
        // Older Hamigo backups know the original Morse timing fields, but none of the new registers.
        val legacy=JSONObject(exported).apply {remove(SyncedAppSettings.FIELD)}.toString()
        SpeechInputPreferences.save(imported.prefs,SpeechInputMode.PUSH_TO_TALK)
        FeedbackPreferences.save(imported.prefs,FeedbackSettings(true,false))
        GameplayPreferences.save(imported.prefs,MorseInputSettings(true,450,true,false))
        SyncedAppSettings.save(imported.prefs,mapOf("autoSync" to true))
        val local=settings(imported)
        imported.import(legacy)
        sameJson(local,settings(imported))
        imported.mergeCloud(legacy)
        sameJson(local,settings(imported))
        assertEquals(SpeechInputMode.PUSH_TO_TALK,SpeechInputPreferences.read(imported.prefs))
        assertEquals(FeedbackSettings(true,false),FeedbackPreferences.read(imported.prefs))
        assertTrue(GameplayPreferences.read(imported.prefs).liveSound)
        assertFalse(GameplayPreferences.read(imported.prefs).autoSpaces)
        assertTrue(imported.prefs.getBoolean("autoSync",false))
    }

    @Test fun eachSettingKeepsItsOwnClockInsteadOfFollowingTheNewestWholePreferenceDocument() {
        val base=progress().export()
        val left=JSONObject().put("interactionSound",record(false,300)).put("speechInputMode",record("ptt",100))
            .put("morseAutoSpaces",record(false,100))
        val right=JSONObject().put("interactionSound",record(true,100)).put("speechInputMode",record("toggle",400))
            .put("morseAutoSpaces",record(true,200))
        fun backup(records:JSONObject,oldPreferenceClock:Long)=JSONObject(base).put(SyncedAppSettings.FIELD,records)
            .put("preferencesUpdatedAt",oldPreferenceClock).toString()
        val a=backup(left,9000)
        val b=backup(right,8000)
        val merged=CloudProgress.merge(a,b)
        assertEquals(merged,CloudProgress.merge(b,a))
        assertEquals(merged,CloudProgress.merge(merged,a))
        val records=JSONObject(merged).getJSONObject(SyncedAppSettings.FIELD)
        assertFalse(records.getJSONObject("interactionSound").getBoolean("value"))
        assertEquals(300,records.getJSONObject("interactionSound").getLong("modifiedAt"))
        assertEquals("toggle",records.getJSONObject("speechInputMode").getString("value"))
        assertEquals(400,records.getJSONObject("speechInputMode").getLong("modifiedAt"))
        assertTrue(records.getJSONObject("morseAutoSpaces").getBoolean("value"))
        val target=progress()
        target.mergeCloud(merged)
        val voiceClock=settings(target).getJSONObject("speechInputMode").getLong("modifiedAt")
        FeedbackPreferences.save(target.prefs,FeedbackSettings(true,true))
        GameplayPreferences.save(target.prefs,MorseInputSettings(liveSound=false,autoSpaces=false))
        assertEquals("Changing sound or Morse must not rewrite the STT choice clock",voiceClock,
            settings(target).getJSONObject("speechInputMode").getLong("modifiedAt"))
    }

    @Test fun anExplicitImportAndLaterLocalChoicesCannotBeRolledBackByTheImportedFutureClock() {
        val target=progress()
        SpeechInputPreferences.save(target.prefs,SpeechInputMode.PUSH_TO_TALK)
        FeedbackPreferences.save(target.prefs,FeedbackSettings(true,true))
        val future=System.currentTimeMillis()+86_400_000
        val oldRemote=JSONObject(target.export()).put(SyncedAppSettings.FIELD,JSONObject()
            .put("speechInputMode",record("toggle",future)).put("interactionSound",record(false,future))
            .put("morseLiveSound",record(false,future)).put("morseAutoSpaces",record(true,future))).toString()
        target.import(oldRemote)
        assertEquals(SpeechInputMode.TOGGLE,SpeechInputPreferences.read(target.prefs))
        SpeechInputPreferences.save(target.prefs,SpeechInputMode.PUSH_TO_TALK)
        FeedbackPreferences.save(target.prefs,FeedbackSettings(true,false))
        GameplayPreferences.save(target.prefs,MorseInputSettings(liveSound=true,autoSpaces=false))
        target.mergeCloud(oldRemote)
        assertEquals("The old imported choice must not reactivate after a later local change",SpeechInputMode.PUSH_TO_TALK,SpeechInputPreferences.read(target.prefs))
        assertEquals(FeedbackSettings(true,false),FeedbackPreferences.read(target.prefs))
        assertTrue(GameplayPreferences.read(target.prefs).liveSound)
        assertFalse(GameplayPreferences.read(target.prefs).autoSpaces)
        assertTrue(target.completed.isEmpty())
        assertEquals(0,target.xp)
    }
    @Test fun concurrentIgnoreAndRealCompletionMergeToOneFinishBonusAndKeepTheRealProof() {
        val base=progress().export()
        val ignoredDevice=progress(1_800_000_000_100)
        val completedDevice=progress(1_800_000_000_200)
        ignoredDevice.import(base);completedDevice.import(base)
        ignoredDevice.setIgnored(setOf("lesson-shared"),true)
        assertEquals(6,completedDevice.complete("lesson-shared"))
        assertEquals(0,ignoredDevice.xp)
        val a=ignoredDevice.export()
        val b=completedDevice.export()
        val merged=CloudProgress.merge(a,b)
        assertEquals(merged,CloudProgress.merge(b,a))
        assertEquals(merged,CloudProgress.merge(merged,a))
        assertEquals(6,state(merged).getInt("xp"))
        val target=progress()
        target.import(merged)
        assertTrue("lesson-shared" in target.completed)
        assertTrue("lesson-shared" in target.pathCompleted)
        target.setIgnored(setOf("lesson-shared"),false)
        assertEquals(0,target.complete("lesson-shared"))
        target.setIgnored(setOf("lesson-shared"),true)
        assertEquals(6,target.xp)
        assertEquals(0,target.totalAnswers)
        assertTrue(target.reviews.isEmpty())
        assertTrue(target.skillReviews.isEmpty())
    }

    @Test fun concurrentIgnoresAndAStaleBackupNeverGenerateXp() {
        val base=progress().export()
        val left=progress(1_800_000_000_300)
        val right=progress(1_800_000_000_200)
        left.import(base);right.import(base)
        val ids=setOf("lesson-same","lesson-other")
        left.setIgnored(ids,true)
        right.setIgnored(setOf("lesson-same"),true)
        val oldLeft=left.export()
        left.setIgnored(setOf("lesson-same"),false)
        val merged=CloudProgress.merge(left.export(),right.export())
        assertEquals(0,state(merged).getInt("xp"))
        assertEquals(merged,CloudProgress.merge(right.export(),left.export()))
        assertEquals(merged,CloudProgress.merge(merged,oldLeft))
        val target=progress()
        target.import(merged)
        assertEquals(setOf("lesson-other"),target.ignored)
        target.setIgnored(setOf("lesson-same"),true)
        assertEquals(0,target.xp)
        target.mergeCloud(oldLeft)
        assertEquals(0,target.xp)
        assertEquals(ids,target.pathCompleted)
        assertTrue(target.completed.isEmpty())
        assertEquals(0,target.totalAnswers)
        assertTrue(target.reviews.isEmpty())
        assertTrue(target.skillReviews.isEmpty())
    }

    @Test fun anOldCompletedBaselineProtectsItsFinishBonusEvenAgainstANewIgnoreAward() {
        val base=JSONObject(progress().export())
        val day="2026-10-21"
        val root=base.getJSONObject("progress")
        root.put("xp",6).put("completed",JSONArray().put("lesson-old"))
            .put("dailyXp",JSONObject().put(day,6))
        root.getJSONObject("syncBase").put("xp",6).put("completed",JSONArray().put("lesson-old"))
            .put("dailyXp",JSONObject().put(day,6))
        val oldBaseline=base.toString()
        val target=progress()
        target.import(oldBaseline)
        target.setIgnored(setOf("lesson-old"),true)
        target.setIgnored(setOf("lesson-old"),false)
        assertEquals(0,target.complete("lesson-old"))
        assertEquals(6,target.xp)
        val other=progress()
        other.setIgnored(setOf("lesson-old"),true)
        val merged=CloudProgress.merge(target.export(),other.export())
        assertEquals("An award already represented in an old completion baseline must not be repaid",6,state(merged).getInt("xp"))
        assertEquals(merged,CloudProgress.merge(other.export(),target.export()))
        target.mergeCloud(merged)
        assertEquals(6,target.xp)
        assertEquals(setOf("lesson-old"),target.completed)
    }

    @Test fun oldSyntheticSkipAwardsAreRemovedWithoutTouchingRealAnswersAndStayRemovedAfterStaleMerges() {
        val at=1_800_000_000_000L
        val source=progress(at)
        source.answer("real-answer",true)
        val original=JSONObject(source.export())
        val originalState=original.getJSONObject("progress")
        val day=StudyDay.date(Instant.ofEpochMilli(at),ZoneOffset.UTC).toString()
        CloudProgress.recordEvent(originalState,day,6,awardKey="lesson:lesson-skipped",at=at)
        originalState.put("xp",9).getJSONObject("dailyXp").put(day,9)
        originalState.put(IgnoredLessons.FIELD,IgnoredLessons.update(null,setOf("lesson-skipped"),true,at))
        val stale=original.toString()
        val eventsBefore=JSONObject(originalState.getJSONObject("syncEvents").toString())
        val local=progress(at)
        assertTrue(local.prefs.edit().putString("progress",state(stale).toString()).commit())
        local.reload()
        assertEquals("An installed local state must be repaired before cloud synchronisation",3,local.xp)
        local.reload();assertEquals("Repairing again must be idempotent",3,local.xp)
        val target=progress(at)
        target.import(stale)
        assertEquals(3,target.xp)
        assertEquals(3,target.todayXp)
        assertEquals(1,target.totalAnswers)
        assertEquals(source.reviews,target.reviews)
        assertEquals(setOf("lesson-skipped"),target.ignored)
        assertTrue(target.completed.isEmpty())
        sameJson(eventsBefore,state(target.export()).getJSONObject("syncEvents"))
        target.setIgnored(setOf("lesson-skipped"),false)
        assertEquals(6,target.complete("lesson-skipped"))
        assertEquals(9,target.xp)
        val corrected=target.export()
        repeat(3) {target.mergeCloud(stale);target.reload();assertEquals(9,target.xp)}
        val merged=CloudProgress.merge(corrected,stale)
        assertEquals(merged,CloudProgress.merge(stale,corrected))
        assertEquals(merged,CloudProgress.merge(merged,stale))
        assertEquals(merged,CloudProgress.merge(merged,merged))
        assertEquals(9,state(merged).getInt("xp"))
        assertEquals(1,state(merged).getInt("answers"))
    }

    @Test fun aRealCompletionWhoseBonusWasSuppressedByAnOldSkipIsPaidOnItsActualDay() {
        val start=1_800_000_000_000L
        val skippedAt=start+86_400_000L
        val completedAt=start+172_800_000L
        fun day(at:Long)=StudyDay.date(Instant.ofEpochMilli(at),ZoneOffset.UTC).toString()
        val source=progress(start)
        source.answer("actual-answer",true)
        val original=JSONObject(source.export())
        val root=original.getJSONObject("progress")
        CloudProgress.recordEvent(root,day(skippedAt),6,awardKey="lesson:lesson-then-completed",at=skippedAt)
        CloudProgress.recordEvent(root,day(completedAt),0,completed="lesson-then-completed",at=completedAt)
        root.put("xp",9).put("completed",JSONArray().put("lesson-then-completed"))
        root.getJSONObject("dailyXp").put(day(skippedAt),6)
        val eventsBefore=JSONObject(root.getJSONObject("syncEvents").toString())
        val target=progress(completedAt)
        target.import(original.toString())
        assertEquals(9,target.xp)
        assertEquals(6,target.todayXp)
        assertEquals(9,target.snapshot().xp)
        assertEquals(0,target.dayXp(java.time.LocalDate.parse(day(skippedAt))))
        assertEquals(3,target.dayXp(java.time.LocalDate.parse(day(start))))
        assertEquals("The skipped-only day must not bridge a study streak",1,target.streak)
        assertEquals(setOf("lesson-then-completed"),target.completed)
        assertEquals(0,target.complete("lesson-then-completed"))
        assertEquals(source.reviews,target.reviews)
        assertEquals(1,target.totalAnswers)
        sameJson(eventsBefore,state(target.export()).getJSONObject("syncEvents"))
        val merged=CloudProgress.merge(target.export(),original.toString())
        assertEquals(merged,CloudProgress.merge(original.toString(),target.export()))
        assertEquals(merged,CloudProgress.merge(merged,original.toString()))
        assertEquals(9,state(merged).getInt("xp"))
        assertEquals(6,state(merged).getJSONObject("dailyXp").getInt(day(completedAt)))
    }

    @Test fun anAmbiguousHistoricalBaselineIsPreservedAndAnUnrelatedZeroXpCompletionIsNotInvented() {
        val old=JSONObject(progress().export())
        val root=old.getJSONObject("progress")
        val day="2026-10-21"
        root.put("xp",17).put("dailyXp",JSONObject().put(day,17))
            .put("completed",JSONArray().put("historical-completion"))
        root.getJSONObject("syncBase").put("xp",17).put("dailyXp",JSONObject().put(day,17))
            .put("completed",JSONArray().put("historical-completion"))
        CloudProgress.recordEvent(root,day,6,awardKey="lesson:unrelated-skip",at=1_800_000_000_000L)
        CloudProgress.recordEvent(root,day,0,completed="unrelated-completion",at=1_800_000_000_001L)
        val today=StudyDay.date(Instant.ofEpochMilli(1_800_000_000_000L),ZoneOffset.UTC).toString()
        CloudProgress.recordEvent(root,today,6,awardKey="lesson:historical-completion",at=1_800_000_000_002L)
        CloudProgress.recordEvent(root,today,0,completed="historical-completion",at=1_800_000_000_003L)
        root.put("xp",29).getJSONObject("dailyXp").put(day,23).put(today,6)
        val target=progress()
        target.import(old.toString())
        assertEquals(17,target.xp)
        assertEquals(17,target.dayXp(java.time.LocalDate.parse(day)))
        assertEquals("An already historical completion must not invent current activity",0,target.todayXp)
        assertEquals(0,target.streak)
        assertEquals(0,target.complete("historical-completion"))
        val merged=CloudProgress.merge(target.export(),old.toString())
        assertEquals(17,state(merged).getInt("xp"))
        assertEquals(17,state(merged).getJSONObject("syncBase").getInt("xp"))
    }

